#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md: the licence and copyright notices of
# everything compiled into the binaries (Go modules) or embedded in the web
# UI (JavaScript runtime packages, fonts). Run it after changing go.mod or
# web/package.json:  ./scripts/third-party-notices.sh
# Needs the Go module cache and web/node_modules (npm ci).
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="$PATH:/usr/local/go/bin"
export GOFLAGS="${GOFLAGS:-} -buildvcs=false"
out=THIRD_PARTY_NOTICES.md

# Licence files of a directory, in a stable order.
licences() {
  find "$1" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'OFL*' \) | LC_ALL=C sort
}

section() { # <title> <directory>
  local title=$1 dir=$2 f
  printf '\n## %s\n' "$title"
  local found=0
  while IFS= read -r f; do
    found=1
    printf '\n### %s\n\n```\n' "$(basename "$f")"
    sed -e 's/\r$//' -e 's/[[:space:]]*$//' "$f"
    printf '```\n'
  done < <(licences "$dir")
  if [[ $found == 0 ]]; then
    echo "no licence file found for $title in $dir" >&2
    exit 1
  fi
}

{
  cat <<'EOF'
# Third-party notices

ES.Topo is distributed under the GNU Affero General Public License v3 (see
`LICENSE`). Its binaries include the third-party software and fonts listed
below, each under its own licence, reproduced here as required by those
licences. This file is generated by `scripts/third-party-notices.sh`.

# Go modules compiled into `estopo` and `essim`
EOF
  # Modules of the packages actually compiled, for the three release targets.
  for target in linux/amd64 windows/amd64 darwin/arm64; do
    GOOS=${target%/*} GOARCH=${target#*/} CGO_ENABLED=0 \
      go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/...
  done | LC_ALL=C sort -u | while read -r path version dir; do
    section "$path $version" "$dir"
  done

  cat <<'EOF'

# JavaScript packages and fonts embedded in the web interface
EOF
  # Runtime dependencies of web/package.json and what they pull in.
  (cd web && npm ls --omit=dev --all --parseable 2>/dev/null) | tail -n +2 | LC_ALL=C sort -u | while read -r dir; do
    name=$(sed -n 's/^  "name": "\(.*\)",$/\1/p' "$dir/package.json" | head -1)
    version=$(sed -n 's/^  "version": "\(.*\)",$/\1/p' "$dir/package.json" | head -1)
    section "$name $version" "$dir"
  done
  # The Svelte runtime is a build dependency whose code ends up in the bundle.
  section "svelte $(sed -n 's/^  "version": "\(.*\)",$/\1/p' web/node_modules/svelte/package.json | head -1)" web/node_modules/svelte
} > "$out"

echo "$out: $(grep -c '^## ' "$out") components, $(wc -c < "$out") bytes"
