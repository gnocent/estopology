const catalogues: Record<'fr' | 'en', Record<Key, string>> = { fr, en };

export type { Key };

/** Translates key, substituting {name} placeholders. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  let s: string = catalogues[prefs.lang][key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Translates a key built at run time (e.g. from an API code), or returns fallback. */
export function tk(key: string, vars: Record<string, string | number> = {}, fallback = key): string {
  if (!(key in fr)) return fallback;
  return t(key as Key, vars);
}
